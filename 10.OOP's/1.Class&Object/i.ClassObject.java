// 1. Creating Class & Objects Without using Constructor Function & Methods

class ClassAndObjectExample1 {
    public static void main(String[] args) {
        // Branch1
        String Branch1 = "BahubaliChai";
        int cupsSold1 = 4;
        int pricePerCup1 = 5;
        int numberOfEmployees1 = 2;

        // Branch2
        String Branch2 = "PokiriJaaga";
        int cupsSold2 = 5;
        int pricePerCup2 = 5;
        int numberOfEmployees2 = 3;

        // Branch3
        String Branch3 = "JalsaKottu";
        int cupsSold3 = 7;
        int pricePerCup3 = 5;
        int numberOfEmployees3 = 4;

        // Branch4
        String Branch4 = "Pushpa";
        int cupsSold4 = 10;
        int pricePerCup4 = 5;
        int numberOfEmployees4 = 5;

        System.out.println(Branch1); // BahubaliChai
        System.out.println(cupsSold1);// 4
        System.out.println(pricePerCup1);// 5
        System.out.println(numberOfEmployees1);// 2

        System.out.println(Branch2);// PokiriJaaga
        System.out.println(cupsSold2);// 5
        System.out.println(pricePerCup2);// 5
        System.out.println(numberOfEmployees2);// 3

        System.out.println(Branch3);// JalsaKottu
        System.out.println(cupsSold3);// 7
        System.out.println(pricePerCup3);// 5
        System.out.println(numberOfEmployees3);// 4

        System.out.println(Branch4);// Pushpa
        System.out.println(cupsSold4);// 10
        System.out.println(pricePerCup4);// 5
        System.out.println(numberOfEmployees4);// 5

    }
}
